// Generates src/bys_tables.h: GF(256) tables (0x11D) and a quarter sine wave in Q15. Usage: node tools/gen_tables.mjs
import { writeFileSync } from 'node:fs';
const exp = new Array(512).fill(0), log = new Array(256).fill(0);
let x = 1;
for (let i = 0; i < 255; i++) { exp[i] = x; log[x] = i; x <<= 1; if (x & 0x100) x ^= 0x11d; }
for (let i = 255; i < 512; i++) exp[i] = exp[i - 255];
const rows = (a, n) => a.map((v, i) => (i % n === 0 ? '\n  ' : ' ') + v + ',').join('');
// 256 intervals per quarter wave; entry 257 repeats entry 256 (the interpolator reads i+1).
const q = []; for (let i = 0; i <= 256; i++) q.push(Math.round(Math.sin((Math.PI / 2) * i / 256) * 32767)); q.push(q[256]);
writeFileSync(new URL('../src/bys_tables.h', import.meta.url),
`/* Generated by tools/gen_tables.mjs. Do not edit by hand. */
#ifndef BYS_TABLES_H
#define BYS_TABLES_H
#include <stdint.h>
/* GF(2^8), polynomial 0x11D, generator 2. Kept in flash (const). */
static const uint8_t BYS_GF_EXP[512] = {${rows(exp, 16)}
};
static const uint8_t BYS_GF_LOG[256] = {${rows(log, 16)}
};
/* Quarter wave of the sine in Q15: 257 points plus one repeated. */
static const int16_t BYS_SIN_Q[258] = {${rows(q, 11)}
};
#endif
`);
