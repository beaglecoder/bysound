// Expected audio: runs the render() logic of web/src/modem/modulator.ts (Float64, exact sine) over the vector symbols
// and writes test/golden/*.i16 (int16 little endian, 1.0 = 32768), plus test/golden_cases.h with the cases.
// Usage: node tools/gen_audio_expected.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const J = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const spec = J('protocol-v4.json'), frames = J('test-vectors/v4-frames.json').vectors, acks = J('test-vectors/v4-acks.json').vectors;

const samples = (s, r) => Math.round(s * r);
// Faithful copy of modulator.ts: render(symbols, band, rate, gapSeconds). `sym` is already doubled in robust.
function render(symbols, b, rate, gapSeconds) {
  const symStart = (k) => Math.round(k * b.sym * rate);
  const out = new Float64Array(symStart(symbols.length) + samples(gapSeconds, rate));
  const ramp = samples(spec.rampSeconds, rate);
  symbols.forEach((tones, k) => {
    const start = symStart(k), len = symStart(k + 1) - start;
    for (let n = 0; n < len; n++) {
      let env = 1;
      if (n < ramp) env = 0.5 * (1 - Math.cos((Math.PI * n) / ramp));
      else if (n >= len - ramp) env = 0.5 * (1 - Math.cos((Math.PI * (len - 1 - n)) / ramp));
      let s = 0;
      tones.forEach((t, g) => { s += Math.sin(((2 * Math.PI * (b.bin + g * 16 + t) * spec.spacingHz) / rate) * n); });
      out[start + n] = s * env * b.amp;
    }
  });
  return out;
}

const pick = {
  ack_mid_44100: [['ack', (v) => v.band === 'mid' && !v.receipt], 44100],
  ref_top_44100: [['frame', (v) => v.name === 'ejemplo' && v.mode === 'reference' && v.band === 'top' && v.set === 0 && v.profile === 'normal'], 44100],
  ref_audible_48000: [['frame', (v) => v.name === 'ejemplo' && v.mode === 'reference' && v.band === 'audible' && v.set === 1 && v.profile === 'normal'], 48000],
  payload_wide_44100: [['frame', (v) => v.name === 'ejemplo' && v.mode === 'payload' && v.band === 'wide'], 44100],
  ref_mid_robust_44100: [['frame', (v) => v.name === 'ejemplo' && v.mode === 'reference' && v.band === 'mid' && v.profile === 'robust'], 44100],
  ref_audible_16000: [['frame', (v) => v.name === 'ejemplo' && v.mode === 'reference' && v.band === 'audible' && v.set === 0 && v.profile === 'normal'], 16000],
  ack_high_44100: [['ack', (v) => v.band === 'high' && v.receipt], 44100],
};

let h = '/* Generated by tools/gen_audio_expected.mjs. */\n#ifndef GOLDEN_CASES_H\n#define GOLDEN_CASES_H\ntypedef struct { const char *id; int is_ack; unsigned index, rate; } golden_case_t;\nstatic const golden_case_t GOLDEN[] = {\n';
for (const [id, [[kind, pred], rate]] of Object.entries(pick)) {
  const list = kind === 'ack' ? acks : frames;
  const index = list.findIndex(pred);
  if (index < 0) throw new Error(id);
  const v = list[index];
  const base = spec.bands[v.band];
  const robust = v.profile === 'robust';
  const b = { bin: base.bin, groups: base.groups, amp: base.toneAmplitude, sym: base.symbolSeconds * (robust ? 2 : 1) };
  const audio = render(v.symbols, b, rate, spec.gapSeconds);
  let peak = 0; for (const x of audio) peak = Math.max(peak, Math.abs(x));
  // The TS (fitLevel) scales down by the real peak; streaming does not know it, so the C scales by the groups*amp bound (only wide exceeds it).
  const bound = b.groups * b.amp, gain = bound > 1 ? 1 / bound : 1;
  const out = Buffer.alloc(audio.length * 2);
  audio.forEach((x, i) => out.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(x * gain * 32768))), i * 2));
  writeFileSync(new URL(`../test/golden/${id}.i16`, import.meta.url), out);
  console.log(`${id}: ${audio.length} samples, TS peak ${peak.toFixed(4)}, bound gain ${gain.toFixed(4)}`);
  h += `  {"${id}", ${kind === 'ack' ? 1 : 0}, ${index}, ${rate}},\n`;
}
h += '};\n#define N_GOLDEN (sizeof GOLDEN / sizeof GOLDEN[0])\n#endif\n';
writeFileSync(new URL('../test/golden_cases.h', import.meta.url), h);
